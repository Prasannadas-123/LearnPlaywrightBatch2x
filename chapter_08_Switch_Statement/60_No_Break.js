let day = 2;

// 1 = Mon ,2 = Tue

switch (day) {
    case 1:
        console.log("Mon");
      
    case 2:
        console.log("Tue");
       
    case 3:
        console.log("Wed");
       
    case 4:
        console.log("Thu");
       
    case 5:
        console.log("Fri");
      
    case 6:
        console.log("Sat");
       
    case 7:
        console.log("Sun");
      
    default:
    console.log("No idea which day is ")
}