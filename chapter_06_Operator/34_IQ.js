//Compound Assignment Operators
let x = 10;
x += 10; // x = x + 10
console.log(x); // Output: 20

x -= 3; // x = x - 3
console.log(x); // Output: 17

x *= 2; // x = x * 2
console.log(x); // Output: 34

x /= 17; // x = x / 17
console.log(x); // Output: 0.5

x %= 2; // x = x % 2
console.log(x); // Output: 0.5




